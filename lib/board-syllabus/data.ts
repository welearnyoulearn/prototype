export type TopicEntry = { topic_name: string; topic_order: number }
export type ChapterEntry = { chapter_name: string; chapter_order: number; topics: TopicEntry[] }
export type SubjectEntry = { subject: string; chapters: ChapterEntry[] }
export type GradeEntry = { grade: string; subjects: SubjectEntry[] }
export type BoardData = { board: string; label: string; grades: GradeEntry[] }

// ─── Helper ───────────────────────────────────────────────────────────────────
function topics(...names: string[]): TopicEntry[] {
  return names.map((topic_name, i) => ({ topic_name, topic_order: i + 1 }))
}
function chapter(chapter_name: string, chapter_order: number, ...topicNames: string[]): ChapterEntry {
  return { chapter_name, chapter_order, topics: topics(...topicNames) }
}
function subject(name: string, chapters: ChapterEntry[]): SubjectEntry {
  return { subject: name, chapters }
}

