export const ALL_BOARDS: BoardData[] = [CBSE, AP_SSC, TS_SSC]

export function getBoardData(board: string): BoardData | undefined {
  return ALL_BOARDS.find(b => b.board === board)
}

export function getGradeData(board: string, grade: string): GradeEntry | undefined {
  return getBoardData(board)?.grades.find(g => g.grade === grade)
}

export function getBoardLabels(): { value: string; label: string }[] {
  return ALL_BOARDS.map(b => ({ value: b.board, label: b.label }))
}
